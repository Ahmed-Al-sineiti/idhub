// بيعمل sites/index.ts تلقائيًا من الفولدرات.
// أي فولدر جوه sites/ فيه site.ts بيتحوّل لصفحة على /<اسم الفولدر>.
// بيتشغّل قبل dev وقبل build (شوف package.json).
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// مسار الفولدر ده هو hub/ مهما كان مكان التشغيل.
const sitesDir = join(dirname(fileURLToPath(import.meta.url)), "..", "sites");

if (!existsSync(sitesDir)) {
  console.error("مفيش فولدر sites");
  process.exit(1);
}

const folders = readdirSync(sitesDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && !entry.name.startsWith(".") && !entry.name.startsWith("_"))
  .map((entry) => entry.name)
  .filter((name) => {
    const hasData = existsSync(join(sitesDir, name, "site.ts"));
    if (!hasData) console.warn(`تخطيت ${name}: مفيش site.ts`);
    return hasData;
  })
  .sort();

const lines = [
  "// AUTO-GENERATED by scripts/generate-sites.mjs — don't edit this file by hand.",
  "// كل فولدر جوه sites/ فيه site.ts بيتحوّل لصفحة على /<اسم الفولدر>.",
  "",
  'import type { SiteData } from "@/lib/site";',
  ...folders.map((folder, i) => `import { site as site${i} } from ${JSON.stringify(`./${folder}/site`)};`),
  "",
  "export const sites: Record<string, SiteData> = {",
  ...folders.map((folder, i) => `  ${JSON.stringify(folder)}: site${i},`),
  "};",
  "",
  "export const siteList = Object.entries(sites).map(([slug, site]) => ({ slug, site }));",
  "",
];

writeFileSync(join(sitesDir, "index.ts"), lines.join("\n"));
console.log(`✓ ${folders.length} sites: ${folders.join(", ")}`);
